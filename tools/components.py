"""The components' documentation, split from daisyUI's official file so an assistant reads only what it needs.

    uv run python tools/components.py         write docs/components/
    uv run python tools/components.py check   fail if it is out of date

Each component becomes one small page with OKF-style frontmatter; its category and status come from app/ui/catalog.py.
Nothing here is interpreted: the official file is cut at its headings. Pages of an organization's own components live
in docs/components/ too, and are kept as they are when their name is not in the official file. It stops rather than
guess: a component missing from the catalogue, a generated page left behind, or a hand-written page on an official
name all need a person.
"""

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from app.ui.catalog import CATEGORIES  # noqa: E402

SOURCE = ROOT / "tools" / "tailwind" / "daisyui-llms.txt"
TARGET = ROOT / "docs" / "components"
DOCUMENTATION = re.compile(r"\[[^\]]+ documentation\]\(https://daisyui\.com/components/([a-z0-9-]+)/\)")
MARKER = "<!-- Generated by tools/components.py. Do not edit. -->"
INDEX_PAGES = ("README", "rules")
LOCAL_RULES = """\
This repository's rules come first. Where this page disagrees with [Standards](../standards.md) or
[AGENTS.md](../../AGENTS.md), they win: no CDN, no npm, no images from other servers, no inline `style` or `onclick`.
Use the [macros](../../app/ui/templates/ui/macros.html) where one exists.
"""


def sections(text: str) -> dict[str, str]:
    """Each component's section, by the name in its official documentation link."""
    start = text.index("## daisyUI components")
    following = re.compile(r"^## ", re.M).search(text, start + 1)
    body = text[start : following.start() if following else len(text)]
    found = {}
    for part in re.split(r"^### ", body, flags=re.M)[1:]:
        match = DOCUMENTATION.search(part)
        if match is None:
            raise ValueError(f"no documentation link in: {part.splitlines()[0]}")
        found[match[1]] = part.rstrip() + "\n"
    return found


def rules(text: str) -> str:
    """The general rules, without the installation that this repository does differently."""
    start = text.index("## daisyUI 5 usage rules")
    end = text.index("### Enable and apply themes")
    if start >= end:
        raise ValueError("the rules section of the official file has changed its order")
    return text[start:end].rstrip() + "\n"


def frontmatter(title: str, description: str, tags: list[str]) -> str:
    return (
        "---\n"
        "type: reference\n"
        f"title: {json.dumps(title, ensure_ascii=False)}\n"
        f"description: {json.dumps(description, ensure_ascii=False)}\n"
        f"tags: [{', '.join(tags)}]\n"
        "---\n\n"
        f"{MARKER}\n\n"
    )


def page(name: str, category: str, status: str, note: str, section: str) -> str:
    lines = section.splitlines()
    title = lines[0].strip()
    description = next((line.strip() for line in lines[1:] if line.strip() and not line.startswith("[")), title)
    if description.startswith("#"):
        raise ValueError(f"{name}: no description before its first heading")
    body = "\n".join(lines[1:])
    body = re.sub(r"^#### ", "## ", body, flags=re.M)
    text = frontmatter(title, description, ["component", category, status])
    text += f"# {title}\n\n**Status:** {status}. **Category:** {category}. **In the demo:** `/gallery/{name}`.\n"
    if note:
        text += f"\n> {note}\n"
    text += f"\n{LOCAL_RULES}\n{body.strip()}\n"
    return text


def index(documented: dict[str, str]) -> str:
    text = frontmatter(
        "Components",
        "Every component on offer, by category, with its status. Read this, then only the pages you need.",
        ["component", "index"],
    )
    text += (
        "# Components\n\n"
        "Read [the general rules](rules.md) once, then only the page of each component you use. The full list, as "
        "data, is in [`catalog.json`](catalog.json).\n"
    )
    for title, group in CATEGORIES.values():
        text += f"\n## {title}\n\n| Component | Status | Use |\n|---|---|---|\n"
        for component in group:
            use = documented[component.name]
            text += f"| [`{component.name}`]({component.name}.md) | {component.status} | {use} |\n"
    return text


def description_of(text: str) -> str:
    """A hand-written page may write it in plain YAML or quoted."""
    head = re.match(r"---\n(.*?)^---$", text, re.M | re.S)
    match = re.search(r"^description:[ \t]*(.*?)[ \t]*$", head[1] if head else "", re.M)
    if match is None or not match[1]:
        raise ValueError("a component page has no description")
    value = match[1]
    if value.startswith('"'):
        return str(json.loads(value))
    if value.startswith("'"):
        return value[1:-1].replace("''", "'")
    return value


def check_pages(official: set[str]) -> None:
    """A page left behind, or a page about to be overwritten: both need a person."""
    for path in TARGET.glob("*.md") if TARGET.exists() else ():
        generated = MARKER in path.read_text(encoding="utf-8")
        if generated and path.stem not in official and path.stem not in INDEX_PAGES:
            raise ValueError(f"{path.name}: generated, but its component left the official file")
        if not generated and path.stem in official:
            raise ValueError(f"{path.name}: written by hand, but the official file has that name now")


def generate() -> dict[str, str]:
    source = SOURCE.read_text(encoding="utf-8")
    found = sections(source)
    check_pages(set(found))
    pages, documented, catalog = {}, {}, []
    for category, (_title, group) in CATEGORIES.items():
        for component in group:
            own = TARGET / f"{component.name}.md"
            if component.name in found:
                content = page(component.name, category, component.status, component.note, found[component.name])
                pages[f"{component.name}.md"] = content
            elif own.exists():
                content = own.read_text(encoding="utf-8")  # an organization's own page: it stays as written
            else:
                raise ValueError(f"{component.name}: no official section and no docs/components/{component.name}.md")
            documented[component.name] = description_of(content)
            catalog.append(
                {
                    "name": component.name,
                    "category": category,
                    "status": component.status,
                    "note": component.note,
                    "use": documented[component.name],
                    "page": f"docs/components/{component.name}.md",
                }
            )
    unlisted = set(found) - {entry["name"] for entry in catalog}
    if unlisted:
        raise ValueError(f"in the official file but not in app/ui/catalog.py: {sorted(unlisted)}")
    pages["README.md"] = index(documented)
    pages["rules.md"] = (
        frontmatter(
            "Component rules",
            "How daisyUI's classes and colours are used. Read once, before using components.",
            ["component", "rules"],
        )
        + f"# Component rules\n\n{LOCAL_RULES}\n{rules(source)}"
    )
    pages["catalog.json"] = json.dumps(catalog, indent=2, ensure_ascii=False) + "\n"
    return pages


def main() -> int:
    pages = generate()
    if sys.argv[1:] == []:
        TARGET.mkdir(parents=True, exist_ok=True)
        for name, content in pages.items():
            (TARGET / name).write_text(content, encoding="utf-8", newline="\n")
        print(f"{len(pages)} files in docs/components/")
        return 0
    if sys.argv[1:] == ["check"]:
        stale = [
            n for n, c in pages.items() if not (TARGET / n).exists() or (TARGET / n).read_text(encoding="utf-8") != c
        ]
        print("\n".join(f"out of date: docs/components/{name}" for name in stale) or "component pages up to date")
        return 1 if stale else 0
    print(__doc__)
    return 2


if __name__ == "__main__":
    sys.exit(main())
